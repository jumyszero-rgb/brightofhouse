export type LpWorkItem =
  | string
  | { text: string; type?: "check" | "caution" | "info" };

export type LpRecommend = {
  name: string;
  price?: string;
  badge?: string;   // 例: "人気No.1"
  note?: string;
};

export type LpMenuItem = {
  name: string;
  price?: string; // 例: "¥9,800"。未定なら "お見積り"
  note?: string;
  compare?: string; // 比較用（例: "他サイト経由 ¥12,000"）任意
  workContent?: string; // 作業内容（改行区切りの箇条書き）。予約マスター連動時のみ使用。
  cautionNote?: string; // 注意事項。予約マスター連動時のみ使用。
};

export type LpFaq = { q: string; a: string };
export type LpVoice = { text: string; who: string; stars?: number };
export type LpReason = { title: string; body: string };
export type LpPhoto = { before: string; after: string; caption?: string };
export type LpStep = { t: string; d: string };

export type LpContent = {
  slug: string;
  serviceLabel: string;
  hero: {
    eyebrow: string;
    title: string;
    subtitle: string;
    priceLead?: string;
    image?: string; // ★ヒーロー背景写真（札幌の実作業写真推奨）
  };
  pains: string[];
  menu: {
    intro?: string;
    campaignBadge?: string;
    items: LpMenuItem[];
    options?: LpMenuItem[];
    baseWork?: LpWorkItem[]     // ← 追加
    setNote?: string;
  };
  reasons: LpReason[];
  faq: LpFaq[];
  voices?: LpVoice[];
  // ★写真を /public/images/lp/ に置いてパスを入れると before/after グリッドが表示される。
  //   空配列のままだとそのセクションは出ない（壊れ画像を出さないため）。
  photos?: LpPhoto[];
  recommended?: LpRecommend[];   // ← 追加
  // ページ固有の「ご利用の流れ」。未指定の場合はBRAND.stepsが使われる。
  steps?: LpStep[];
};

